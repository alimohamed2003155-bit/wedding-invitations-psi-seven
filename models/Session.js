// models/Session.js
// جلسة دخول واحدة.
//
// ليه جلسة في الداتابيز مش JWT: الـ JWT مبيتلغيش — لو حد سرق واحد،
// بيفضل شغال لحد ما ينتهي بنفسه ومفيش حاجة تقدر توقفه. الجلسة هنا
// بنقدر نلغيها في نفس اللحظة (تسجيل خروج حقيقي، حظر حساب، جلسة
// مسروقة)، وده أهم بكتير من توفير استعلام.
//
// ===== إزاي الجلسة بتفضل شغالة فترة طويلة وبأمان في نفس الوقت =====
//
// 1) التوكن **مبيتخزنش** — بنخزّن بصمته (sha256) بس. لو الداتابيز
//    تسرّبت، اللي فيها مايفتحش أي حساب.
//
// 2) صلاحية متجددة (sliding): كل ما العميل يستخدم الموقع بتتمدّد.
//    يعني اللي بيدخل من وقت للتاني مبيتطلبش منه تسجيل دخول تاني أبدًا.
//
// 3) تدوير التوكن (rotation): التوكن نفسه بيتغيّر كل فترة حتى والجلسة
//    شغالة. فلو حد نسخ الكوكي، النسخة اللي معاه بتبطل لوحدها.
//
// 4) كشف إعادة الاستخدام (reuse detection): لما التوكن يتدوّر بنفتكر
//    بصمة القديم. لو حد جه بتوكن قديم بعد فترة السماح، يبقى فيه نسختين
//    من نفس الجلسة — يعني سرقة. ساعتها بنلغي الجلسة كلها فورًا،
//    فالحرامي والأصلي الاتنين بيتقفلوا والعميل بيسجّل دخول من تاني.
//
// 5) سقف مطلق: مهما اتجددت، الجلسة ليها عمر أقصى. ده بيحد الضرر لو
//    حاجة فاتت من الأربعة اللي فوق.
const mongoose = require('mongoose');

const sessionSchema = new mongoose.Schema({
  // بصمة التوكن الحالي — مش التوكن نفسه
  tokenHash: { type: String, index: true, sparse: true, unique: true },

  // التوكن القديم بعد آخر تدوير. بيفضل مقبول لفترة سماح قصيرة عشان
  // الطلبات اللي كانت طايرة وقت التدوير ماتفشلش، وبعدها أي استخدام
  // ليه = سرقة.
  prevTokenHash: { type: String, index: true, sparse: true },
  graceUntil: { type: Date, default: null },

  // كل تدويرات نفس تسجيل الدخول بتشترك في الرقم ده — لما نكتشف سرقة
  // بنلغي العيلة كلها مش التوكن الواحد
  familyId: { type: String, index: true },

  // الجلسات القديمة (قبل التحديث) كانت بتخزّن التوكن كنص صريح.
  // بنسيب الحقل عشان اللي مسجّل دلوقتي مايتقفلش عليه، وأول ما يستخدم
  // الموقع بتتحوّل جلسته للشكل الجديد لوحدها.
  token: { type: String, index: true, sparse: true },

  userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },

  createdAt: { type: Date, default: Date.now },
  lastUsedAt: { type: Date, default: Date.now },
  rotatedAt: { type: Date, default: Date.now },

  // الصلاحية المتجددة — TTL بيمسح الجلسة تلقائيًا بعدها
  expiresAt: { type: Date, required: true },
  // السقف المطلق — مهما اتجددت مبتعديهوش
  absoluteExpiresAt: { type: Date, default: null },
});

sessionSchema.index({ expiresAt: 1 }, { expireAfterSeconds: 0 });

module.exports = mongoose.model('Session', sessionSchema);
